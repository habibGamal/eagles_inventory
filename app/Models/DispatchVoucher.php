<?php

namespace App\Models;

use App\Enums\DocumentStatus;
use Database\Factories\DispatchVoucherFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\MorphMany;
use Illuminate\Support\Carbon;

/**
 * @property int $id
 * @property int $warehouse_id
 * @property int $sector_id
 * @property int|null $recipient_employee_id
 * @property string $recipient_name_snapshot
 * @property int $issued_by
 * @property Carbon $issue_date
 * @property string|null $notes
 * @property DocumentStatus $status
 * @property int $created_by
 * @property int|null $approved_by
 * @property Carbon|null $approved_at
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
#[Fillable([
    'warehouse_id',
    'sector_id',
    'recipient_employee_id',
    'recipient_name_snapshot',
    'issued_by',
    'issue_date',
    'notes',
    'status',
    'created_by',
    'approved_by',
    'approved_at',
])]
class DispatchVoucher extends Model
{
    /** @use HasFactory<DispatchVoucherFactory> */
    use HasFactory;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'issue_date' => 'date',
            'approved_at' => 'datetime',
            'status' => DocumentStatus::class,
        ];
    }

    /**
     * Get the source warehouse.
     *
     * @return BelongsTo<Warehouse, $this>
     */
    public function warehouse(): BelongsTo
    {
        return $this->belongsTo(Warehouse::class);
    }

    /**
     * Get the destination sector.
     *
     * @return BelongsTo<Sector, $this>
     */
    public function sector(): BelongsTo
    {
        return $this->belongsTo(Sector::class);
    }

    /**
     * Get the employee recipient if assigned.
     *
     * @return BelongsTo<Employee, $this>
     */
    public function recipientEmployee(): BelongsTo
    {
        return $this->belongsTo(Employee::class, 'recipient_employee_id');
    }

    /**
     * Get the warehouse user who issued the stock.
     *
     * @return BelongsTo<User, $this>
     */
    public function issuedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'issued_by');
    }

    /**
     * Get the user who created the dispatch voucher.
     *
     * @return BelongsTo<User, $this>
     */
    public function createdBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /**
     * Get the user who approved the dispatch voucher.
     *
     * @return BelongsTo<User, $this>
     */
    public function approvedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'approved_by');
    }

    /**
     * Get line items for this dispatch voucher.
     *
     * @return HasMany<DispatchVoucherItem, $this>
     */
    public function items(): HasMany
    {
        return $this->hasMany(DispatchVoucherItem::class);
    }

    /**
     * Get all stock movements generated by this dispatch voucher.
     *
     * @return MorphMany<StockMovement, $this>
     */
    public function stockMovements(): MorphMany
    {
        return $this->morphMany(StockMovement::class, 'reference');
    }
}
